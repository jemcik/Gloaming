# ── theme toggle ───────────────────────────────────────────────────────────
# Applied from an inline head script too, so the page never paints the wrong
# theme first. Three states because Settings has three; "system" is a stored
# value like the others rather than the absence of one.
JS = """// Generated by tools/build_site.py - edit there, not here.
(function () {
  var KEY = 'gloaming-theme', ORDER = ['system', 'dawn', 'dusk'];
  function read() {
    try { return localStorage.getItem(KEY) || 'system'; } catch (e) { return 'system'; }
  }
  function apply(v) {
    var r = document.documentElement;
    if (v === 'system') r.removeAttribute('data-theme'); else r.setAttribute('data-theme', v);
  }
  function label(btn, v) {
    btn.setAttribute('aria-label', btn.dataset['label' + v.charAt(0).toUpperCase() + v.slice(1)] || v);
    btn.querySelector('.theme-name').textContent =
      btn.dataset['name' + v.charAt(0).toUpperCase() + v.slice(1)] || v;
  }
  document.addEventListener('DOMContentLoaded', function () {
    var btn = document.querySelector('.theme');
    if (!btn) return;
    var cur = read();
    label(btn, cur);
    btn.addEventListener('click', function () {
      cur = ORDER[(ORDER.indexOf(cur) + 1) % ORDER.length];
      try { localStorage.setItem(KEY, cur); } catch (e) {}
      apply(cur);
      label(btn, cur);
    });
  });
})();
"""

