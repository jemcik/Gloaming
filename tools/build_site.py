"""Build the Gloaming site into docs/, for GitHub Pages.

Six pages - a landing page and a privacy policy, in English, Ukrainian and
Russian - from ONE template each. Hand-writing six files means six files
drifting: a section added to the English page and forgotten in the other two is
not a thing anyone notices until a Ukrainian reader is missing a paragraph.
Here the structure is written once and the strings are a table, so a missing
translation is a KeyError at build time rather than a hole on a live page.

The palette and the type are lifted from Theme.kt so the site and the app agree.
Two themes, as the app has: the page follows the OS by default and the toggle
overrides it, which is Settings' own Dusk / Dawn / system choice.

FONTS. Neither bundled font has a single Cyrillic glyph - figtree.ttf carries
391 codepoints and baloo2.ttf 856, Latin both. So the Ukrainian and Russian
pages CANNOT be set in Figtree, and the stack names Golos Text after it: the
browser falls back per glyph, so Latin words keep the brand face and Cyrillic
gets a family designed for it, rather than whatever the OS happens to reach for.
The app has the same gap and no such fallback; see the note in the site commit.

URLS ARE LOAD-BEARING. docs/privacy-policy.html is the address given to Google
Play, so that file must keep its name and its place at the root. The translated
copies live under uk/ and ru/ rather than the English one moving.

Run from anywhere:  python3 tools/build_site.py
"""
